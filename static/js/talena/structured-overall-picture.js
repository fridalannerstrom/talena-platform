/* #355: structured Overall picture. The old Markdown stays readable until
   a structured version has been explicitly generated by the user. */
(function () {
  "use strict";
  const SECTIONS = [
    ["skills", "Färdighet", "Skills"],
    ["motivation", "Motivation", "Motivation"],
    ["personality", "Personlighet", "Personality"],
    ["synthesis", "Helhetsbild", "Overall picture"],
  ];
  const sv = () => (document.documentElement.lang || "").toLowerCase().startsWith("sv");
  const tr = (s, e) => sv() ? s : e;
  const el = (tag, cls, value) => {
    const node = document.createElement(tag);
    if (cls) node.className = cls;
    if (value !== undefined) node.textContent = value;
    return node;
  };
  const token = () => {
    const cookie = document.cookie.split("; ").find(x => x.startsWith("csrftoken="));
    return cookie ? decodeURIComponent(cookie.slice(10)) : "";
  };
  const getSaved = (source) => {
    const script = source?.querySelector('script[id="talena-overall-picture-structured"]');
    if (!script?.textContent?.trim()) return {};
    try {
      const parsed = JSON.parse(script.textContent);
      return parsed && parsed.schema === 1 ? parsed : {};
    } catch (_error) { return {}; }
  };
  const addParagraphs = (target, content) => {
    const paragraphs = String(content || "").trim().split(/\n\s*\n/).filter(Boolean);
    if (!paragraphs.length) target.appendChild(el("p", "after-interview-overall__muted",
      tr("Inget innehåll ännu.", "No content yet.")));
    paragraphs.forEach(text => target.appendChild(el("p", "after-interview-overall__paragraph", text.trim())));
  };

  function createCard(panel, source, legacy, heading, description, root) {
    const card = el("section", "after-interview-tab-card after-interview-overall");
    card.dataset.overallPictureStructuredCard = "true";
    const header = el("div", "after-interview-tab-card__header");
    const kicker = el("div", "after-interview-tab-card__eyebrow",
      "✦ " + tr("AI-genererat underlag", "AI-generated evidence"));
    header.append(
      kicker,
      el("h3", "after-interview-tab-card__title", heading),
      el("p", "after-interview-tab-card__description", description)
    );
    const layout = el("div", "after-interview-overall__layout");
    const message = el("div", "alert alert-danger d-none mt-3");
    message.setAttribute("role", "alert");
    card.append(header, message, layout);

    let state = getSaved(source);
    let busy = false;
    const statusText = {
      generating: tr("Genereras…", "Generating…"),
      completed: tr("Klar", "Ready"),
      failed: tr("Misslyckades, försök igen", "Failed, retry"),
      outdated: tr("Behöver uppdateras", "Needs update"),
      not_applicable: tr("Inget testresultat för området", "No assessment results for this area"),
      not_started: tr("Inte genererad", "Not generated"),
    };

    const generate = async (category, button) => {
      if (busy) return;
      busy = true;
      button.disabled = true;
      button.setAttribute("aria-busy", "true");
      message.classList.add("d-none");
      button.textContent = tr("Skapar…", "Generating…");
      try {
        const base = root?.dataset.postInterviewRegenerateUrl;
        if (!base) throw new Error(tr("Kunde inte hitta genereringsadressen.", "No generation endpoint available."));
        const endpoint = new URL(base, window.location.origin);
        endpoint.searchParams.set("block", "overall_picture");
        endpoint.searchParams.set("structured", "1");
        endpoint.searchParams.set("section", category);
        const start = await fetch(endpoint, {
          method: "POST", credentials: "same-origin",
          headers: { "X-CSRFToken": token(), "X-Requested-With": "XMLHttpRequest",
            "Content-Type": "application/json" },
          body: "{}",
        });
        const init = await start.json();
        if (!start.ok) throw new Error(init.error || tr("Kunde inte starta.", "Could not start."));
        const result = await fetch(init.stream_url, {
          credentials: "same-origin",
          headers: { Accept: "application/x-ndjson", "X-Requested-With": "XMLHttpRequest" },
        });
        if (!result.ok || !result.body) throw new Error(tr("Kunde inte läsa AI-svaret.", "Could not read AI response."));
        const reader = result.body.getReader();
        const decoder = new TextDecoder("utf-8");
        let buffer = "";
        let latestState = null;
        let failed = false;
        const consume = line => {
          if (!line.trim()) return;
          const event = JSON.parse(line);
          if (event.type === "structured_result") latestState = event.data;
          if ((event.type === "structured_section_error" || event.type === "structured_item_error")
              && event.section === category) failed = true;
          if (event.type === "error") throw new Error(event.message || tr("Genereringen misslyckades.", "Generation failed."));
        };
        while (true) {
          const chunk = await reader.read();
          if (chunk.done) break;
          buffer += decoder.decode(chunk.value, { stream: true });
          const lines = buffer.split("\n");
          buffer = lines.pop() || "";
          lines.forEach(consume);
        }
        buffer += decoder.decode();
        if (buffer.trim()) consume(buffer);
        if (latestState) state = latestState;
        render();
        if (failed || !latestState) throw new Error(tr(
          "En eller flera delar kunde inte genereras. Tidigare text finns kvar.",
          "Some items could not be generated. Earlier text is preserved."
        ));
      } catch (error) {
        message.textContent = error.message || tr("Genereringen misslyckades.", "Generation failed.");
        message.classList.remove("d-none");
      } finally {
        busy = false;
        button.disabled = false;
        button.removeAttribute("aria-busy");
        render();
      }
    };

    const render = () => {
      layout.replaceChildren();
      const sections = state.sections || {};
      if (!Object.keys(sections).length && legacy?.textContent?.trim()) {
        const older = el("section", "after-interview-overall__legacy");
        older.append(
          el("h4", "after-interview-overall__group-title", tr("Tidigare Helhetsbild", "Previous Overall picture")),
          el("p", "after-interview-overall__muted", tr(
            "Din tidigare rapport finns kvar. Generera en ny strukturerad version när du vill.",
            "Your existing report is preserved. Generate a structured version when ready."
          ))
        );
        legacy.classList.add("after-interview-tab-card__body");
        older.appendChild(legacy);
        layout.appendChild(older);
      }
      SECTIONS.forEach(([key, swedish, english]) => {
        const section = sections[key] || {};
        const area = el("section", "after-interview-overall__group");
        area.dataset.overallPictureSection = key;
        const row = el("div", "after-interview-overall__group-header");
        const left = el("div", "after-interview-overall__heading");
        left.append(
          el("h4", "after-interview-overall__group-title", tr(swedish, english)),
          el("span", "after-interview-overall__status", statusText[section.status] || statusText.not_started)
        );
        const button = el("button", "btn btn-outline-primary btn-sm",
          section.status === "completed" ? tr("Generera igen", "Regenerate") : tr("Generera", "Generate"));
        button.type = "button";
        button.disabled = busy;
        button.addEventListener("click", () => generate(key, button));
        row.append(left, button);
        area.appendChild(row);

        if (key === "synthesis") {
          if (section.text) {
            const body = el("div", "after-interview-overall__synthesis");
            addParagraphs(body, section.text);
            area.appendChild(body);
          }
        } else {
          for (const item of section.items || []) {
            const box = el("article", "after-interview-overall__item");
            box.appendChild(el("h5", "after-interview-overall__item-title", item.title));
            if (item.status !== "completed") {
              box.appendChild(el("p", "after-interview-overall__muted",
                statusText[item.status] || statusText.not_started));
            }
            if (item.testbild) {
              box.appendChild(el("h6", "after-interview-overall__subheading", "Testbild"));
              addParagraphs(box, item.testbild);
            }
            if (item.intervjun) {
              box.appendChild(el("h6", "after-interview-overall__subheading", tr("Intervjun", "Interview")));
              addParagraphs(box, item.intervjun);
            }
            area.appendChild(box);
          }
        }
        layout.appendChild(area);
      });
    };
    render();
    return card;
  }

  window.TalenaStructuredOverallPicture = Object.freeze({ createCard });
})();
