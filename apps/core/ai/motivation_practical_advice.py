"""Approved, bilingual MQ guidance shared by the manager report and AI.

The canonical JSON is the single source of truth. None of the tips is
generated by a model or stored per candidate.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path


_SOURCE = Path(__file__).with_name("reference_data") / "motivation_practical_advice.json"


@lru_cache(maxsize=1)
def get_motivation_practical_advice() -> dict:
    data = json.loads(_SOURCE.read_text(encoding="utf-8"))
    if set(data) != {"sv", "en"}:
        raise ValueError("MQ guidance must provide Swedish and English.")
    keys = set(data["sv"])
    if len(keys) != 20 or set(data["en"]) != keys:
        raise ValueError("MQ guidance must cover the same 20 factors in both languages.")
    for language, factors in data.items():
        for key, tips in factors.items():
            if not isinstance(tips, dict) or any(
                not isinstance(tips.get(kind), list)
                or len(tips[kind]) != 2
                or not all(isinstance(text, str) and text.strip() for text in tips[kind])
                for kind in ("do", "avoid")
            ):
                raise ValueError(f"Invalid MQ guidance: {language}/{key}")
    return data
