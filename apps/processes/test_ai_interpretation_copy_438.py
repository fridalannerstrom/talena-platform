class AIInterpretationNoticeCopyTests(SimpleTestCase):
    def _notice(self, area, language, interpretation):
        config = AREAS[area]
        context = dict(config["context"])
        context[config["context_key"]] = {
            "title": "Existing saved title",
            "interpretation": interpretation,
        }
        with override(language):
            html = render_to_string(config["template"], context)
        self.assertIn("<!-- AI / EVIDENCE NOTE -->", html)
        self.assertIn("<!-- OVERALL INTERPRETATION -->", html)
        return html.split("<!-- AI / EVIDENCE NOTE -->", 1)[1].split(
            "<!-- OVERALL INTERPRETATION -->", 1,
        )[0]

    def test_exact_swedish_copy_and_two_paragraphs_with_unchanged_info_box(self):
        for area, config in AREAS.items():
            with self.subTest(area=area):
                notice = self._notice(area, "sv", "Sparad AI-tolkning")
                self.assertIn(config["sv"], notice)
                self.assertIn(RESPONSIBILITY_SV, notice)
                self.assertNotIn(config["old"], notice)
                self.assertEqual(notice.count("<p "), 2)
                self.assertIn('<p class="mb-2">', notice)
                self.assertIn('<p class="mb-0">', notice)
                self.assertEqual(notice.count("Om AI-tolkningen"), 1)
                self.assertIn('data-feather="info"', notice)
                self.assertIn("personality-questions-context-note", notice)

    def test_english_copy_translates_meaning_with_same_layout(self):
        for area, config in AREAS.items():
            with self.subTest(area=area):
                notice = self._notice(area, "en", "Saved AI interpretation")
                self.assertIn(config["en"], notice)
                self.assertIn(RESPONSIBILITY_EN, notice)
                self.assertIn("About the AI interpretation", notice)
                self.assertEqual(notice.count("<p "), 2)
                self.assertNotIn("Du ansvarar", notice)
                self.assertNotIn(config["sv"], notice)

    def test_static_notice_is_not_changed_by_regenerating_interpretation(self):
        for area in AREAS:
            with self.subTest(area=area):
                before = self._notice(area, "sv", "Gamla AI-resultat")
                after = self._notice(area, "sv", "Nya AI-resultat efter omgenerering")
                self.assertEqual(before, after)
